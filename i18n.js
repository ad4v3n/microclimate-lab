    function t(key, params = {}) {
        const langDict = dict[currentLang] || dict.ru;
        let text = langDict[key] || dict.ru[key] || key;

        if (typeof text === 'string' && params) {
            Object.keys(params).forEach(p => {
                text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
            });
        }
        return text;
    }

    function setLang(lang) {
        if (lang !== 'ru' && lang !== 'kz') return;
        currentLang = lang;
        try {
            if (typeof localStorage !== 'undefined') {
                localStorage.setItem(STORAGE_KEY, lang);
            }
        } catch (e) { /* ignore */ }

        if (typeof document !== 'undefined') {
            document.documentElement.lang = lang === 'kz' ? 'kk' : 'ru';
            document.title = t('pageTitle');
            updateDOM();
        }

        listeners.forEach(fn => {
            try { fn(currentLang); } catch (err) { console.error('i18n listener error:', err); }
        });
    }

    function getLang() {
        return currentLang;
    }

    function onLanguageChange(fn) {
        listeners.push(fn);
    }

    function updateDOM() {
        if (typeof document === 'undefined') return;

        // Elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.dataset.i18n;
            if (key) {
                const translation = t(key);
                if (translation) {
                    el.innerHTML = translation;
                }
            }
        });

        // Elements with data-i18n-title
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.dataset.i18nTitle;
            if (key) {
                el.title = t(key);
            }
        });

        // Elements with data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.dataset.i18nPlaceholder;
            if (key) {
                el.placeholder = t(key);
            }
        });

        // Sync switcher buttons
        document.querySelectorAll('.lang-btn').forEach(btn => {
            if (btn.dataset.lang === currentLang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    }

    return {
        t,
        setLang,
        getLang,
        dict,
        data: dataTranslations,
        onLanguageChange,
        updateDOM
    };
